from typing import Protocol
from thermosys.state import State

class Fluid(Protocol):
    name: str
    T_min: float
    T_max: float
    def state_TP(self, T: float, P: float) -> State: ...
    def state_PH(self, P: float, h: float) -> State: ...
    def state_PS(self, P: float, s: float) -> State: ...
    def state_PQ(self, P: float, Q: float) -> State: ...
    def rho(self, T: float, P: float) -> float: ...
    def cp(self, T: float, P: float) -> float: ...
    def mu(self, T: float, P: float) -> float: ...
    def k(self, T: float, P: float) -> float: ...
    def Pr(self, T: float, P: float) -> float: ...
